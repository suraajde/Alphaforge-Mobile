    result = service.generate_recommendations(candidates=cand_res)







    assert result.total_recommendations == 1



    assert audit_svc.saved_trail is not None



    assert audit_svc.saved_trail.total_entries == 1



    assert audit_svc.saved_trail.entries[0].category == "REBALANCING_RECOMMENDATION"
